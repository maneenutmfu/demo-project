var สิทธิ์ตามบทบาท = {
  ยื่นใบลาใหม่: ["employee"],
  ดูใบลาทุกใบ: ["manager", "hr"],
  เปลี่ยนสถานะใบลา: ["manager", "hr"],
  เขียนความเห็นทุกใบ: ["manager", "hr"],
  จัดการประเภทการลา: ["hr"]
};

function ตรวจสิทธิ์(การกระทำ, บทบาท) {
  var รายชื่อ = สิทธิ์ตามบทบาท[การกระทำ];
  return !!รายชื่อ && รายชื่อ.indexOf(บทบาท) !== -1;
}
